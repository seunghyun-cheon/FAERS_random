"""Generate data.js from data/FAERS_ATC_SMQ_pool.xlsx (sheets ATC_40, SMQ_30)."""
import json, sys, pathlib, openpyxl

root = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "data" / "FAERS_ATC_SMQ_pool.xlsx"
wb = openpyxl.load_workbook(src, read_only=True)

def rows(name):
    it = wb[name].iter_rows(values_only=True)
    next(it)
    return [r for r in it if r and r[0]]

atc = [dict(id=r[0], code=r[1], name=r[2], area=r[3], url=r[4]) for r in rows("ATC_40")]
smq = [dict(id=r[0], name=r[1], ko=r[2], area=r[3], url=r[4]) for r in rows("SMQ_30")]
assert len({a["id"] for a in atc}) == len(atc) and len({s["id"] for s in smq}) == len(smq)
out = "// Auto-generated by scripts/build_data.py - do not edit by hand.\n"
out += "window.POOL = " + json.dumps({"atc": atc, "smq": smq}, ensure_ascii=False, indent=1) + ";\n"
(root / "data.js").write_text(out, encoding="utf-8")
print(f"ATC {len(atc)}, SMQ {len(smq)} -> data.js")
